/* Report export: render the current analysis as Markdown for copy/download. */

function reportFilename(vehicle) {
  const v = vehicle || {};
  const parts = [v.year, v.make, v.model]
    .filter(Boolean)
    .map((s) => String(s).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, ""))
    .filter(Boolean);
  return "carlens-" + (parts.length ? parts.join("-") : "car-report") + ".md";
}

function fmtIssueMd(item) {
  if (typeof item === "string") return item;
  const parts = [item.issue || JSON.stringify(item)];
  if (item.typical_mileage) parts.push("typically around " + item.typical_mileage);
  if (item.symptoms) parts.push("signs: " + item.symptoms);
  if (item.severity) parts.push("severity: " + item.severity);
  return parts.join(" — ");
}

function fmtMaintMd(m) {
  if (typeof m === "string") return m;
  if (m && (m.interval || m.item)) {
    return (m.interval || "as needed") + ": " + (m.item || "") + " (" + (m.priority || "normal") + ")";
  }
  return JSON.stringify(m);
}

function mdList(items, format) {
  if (!items || !items.length) return "_None reported._\n";
  return items.map((it) => "- " + (format ? format(it) : String(it))).join("\n") + "\n";
}

function oneLine(s) {
  return String(s || "").replace(/\s+/g, " ").trim();
}

function buildReportMarkdown(input) {
  const { report, nhtsa, listing, fields, generatedAt } = input || {};
  const v = (report && report.vehicle) || {};
  const f = fields || {};
  const titleBits = [v.year || f.year, v.make || f.make, v.model || f.model, v.trim].filter(Boolean);
  const title = titleBits.length ? titleBits.join(" ") : "Vehicle report";
  const url = f.url || (listing && listing.url) || "";
  const L = [];
  L.push("# " + title);
  L.push("");
  const sub = [];
  if (v.generation) sub.push(v.generation);
  if (v.mileage || f.mileage) sub.push("mileage " + (v.mileage || f.mileage));
  if (v.price || f.price) sub.push("price " + (v.price || f.price));
  if (v.location) sub.push(v.location);
  if (sub.length) {
    L.push(sub.join(" · "));
    L.push("");
  }
  if (url) {
    L.push("Source: " + url);
    L.push("");
  }
  L.push("## Vehicle");
  L.push("");
  L.push("- Year: " + (oneLine(v.year || f.year) || "?"));
  L.push("- Make: " + (oneLine(v.make || f.make) || "?"));
  L.push("- Model: " + (oneLine(v.model || f.model) || "?"));
  if (v.trim) L.push("- Trim: " + oneLine(v.trim));
  if (v.generation) L.push("- Generation: " + oneLine(v.generation));
  L.push("");
  L.push("## Known issues");
  L.push("");
  L.push(mdList(report && report.known_issues, fmtIssueMd));
  L.push("## Maintenance schedule");
  L.push("");
  L.push(mdList(report && report.maintenance_schedule, fmtMaintMd));
  L.push("## Questions to ask the seller");
  L.push("");
  L.push(mdList(report && report.seller_questions));
  L.push("## Red flags");
  L.push("");
  L.push(mdList(report && report.red_flags));
  L.push("## Recalls & complaints (NHTSA)");
  L.push("");
  if (!nhtsa || nhtsa.error === "need year/make/model") {
    L.push("_NHTSA data unavailable._\n");
  } else if (nhtsa.notFound) {
    const q = nhtsa.queried || {};
    L.push(`_No NHTSA records matched ${[q.year, q.make, q.model].filter(Boolean).join(" ") || "this vehicle"}._\n`);
  } else {
    L.push(`_${(nhtsa.recalls || []).length} recall(s), ${nhtsa.totalComplaints || 0} complaint(s) on file._`);
    L.push("");
    if ((nhtsa.recalls || []).length) {
      for (const r of nhtsa.recalls.slice(0, 10)) {
        L.push(`- Recall [${r.campaign || "?"}] ${oneLine(r.component)}: ${oneLine(r.summary).slice(0, 300)}`);
      }
    }
    if ((nhtsa.topComponents || []).length) {
      for (const c of nhtsa.topComponents.slice(0, 8)) {
        L.push(`- Complaints about ${oneLine(c.component)}: ${c.count} in sample`);
      }
    }
    L.push("");
  }
  if (report && report.seller_message_draft) {
    L.push("## Seller message draft");
    L.push("");
    L.push("```");
    L.push(String(report.seller_message_draft).trim());
    L.push("```");
    L.push("");
  }
  if (report && report.notes) {
    L.push("## Notes");
    L.push("");
    L.push(oneLine(report.notes));
    L.push("");
  }
  L.push(`_Generated by CarLens on ${generatedAt || new Date().toLocaleString()}._`);
  L.push("");
  return L.join("\n");
}

if (typeof module !== "undefined" && module.exports) {
  module.exports = { buildReportMarkdown, reportFilename };
}
